package com.acme.trainingportal;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.CommandLineRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
public class StartupData implements CommandLineRunner {
    private final JdbcTemplate jdbcTemplate;
    private final Path documentRoot;

    public StartupData(JdbcTemplate jdbcTemplate, @Value("${acme.document-root}") String documentRoot) {
        this.jdbcTemplate = jdbcTemplate;
        this.documentRoot = Path.of(documentRoot);
    }

    public void run(String... args) throws IOException {
        jdbcTemplate.execute("DROP TABLE IF EXISTS comments");
        jdbcTemplate.execute("DROP TABLE IF EXISTS courses");
        jdbcTemplate.execute("DROP TABLE IF EXISTS users");
        jdbcTemplate.execute("CREATE TABLE courses (id INT PRIMARY KEY, tenant VARCHAR(40), title VARCHAR(120), instructor VARCHAR(80), summary CLOB, published BOOLEAN)");
        jdbcTemplate.execute("CREATE TABLE comments (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, course_id INT, author VARCHAR(80), body CLOB)");
        jdbcTemplate.execute("CREATE TABLE users (id INT PRIMARY KEY, username VARCHAR(80), password VARCHAR(80), tenant VARCHAR(40), role VARCHAR(40))");
        jdbcTemplate.update("INSERT INTO courses VALUES (1, 'northwind', 'Secure Coding Fundamentals', 'Avery Chen', 'A practical onboarding course for developers.', TRUE)");
        jdbcTemplate.update("INSERT INTO courses VALUES (2, 'northwind', 'Incident Review Workshop', 'Sam Rivera', 'Review production incidents and remediation plans.', TRUE)");
        jdbcTemplate.update("INSERT INTO courses VALUES (3, 'contoso', 'Cloud Cost Controls', 'Morgan Lee', 'Finance operations training for platform teams.', TRUE)");
        jdbcTemplate.update("INSERT INTO comments (course_id, author, body) VALUES (1, 'morgan', 'Add this to the new hire checklist.')");
        jdbcTemplate.update("INSERT INTO comments (course_id, author, body) VALUES (1, 'admin', '<strong>Required</strong> before repository access.')");
        jdbcTemplate.update("INSERT INTO users VALUES (1, 'admin', 'admin123', 'northwind', 'admin')");
        jdbcTemplate.update("INSERT INTO users VALUES (2, 'morgan', 'training', 'northwind', 'learner')");
        Files.createDirectories(documentRoot);
        Files.writeString(documentRoot.resolve("onboarding.txt"), "Welcome to Acme Training Portal.\n");
        Files.writeString(documentRoot.resolve("northwind-plan.txt"), "Northwind enablement plan\n");
    }
}
